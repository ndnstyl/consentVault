"""Writes tests/projection/INDEX.md: every spec item of pure-projection.md (draft 6) mapped to its test ids and its current failure line.

Run from the repository root with the suite's interpreter and PG_BIN set:
    PG_BIN=<postgres bin dir> python tests/projection/make_index.py
Exit 1 when any test fails for a reason other than a missing feature (a defect in the test), or any numbered cutover item has no test.
Not a test: pytest does not collect it."""

from __future__ import annotations

import re
import sys
from collections import defaultdict
from pathlib import Path

import pytest

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
NUMBER = re.compile(r"^(?:item)?(\d{1,2})(?:\.|$)")


class Collector:
    def __init__(self):
        self.ids, self.line = {}, {}

    def pytest_collection_modifyitems(self, items):
        for it in items:
            self.ids[it.nodeid] = [a for m in it.iter_markers("spec_item") for a in m.args]

    def pytest_runtest_logreport(self, report):
        if report.when == "call" or (report.when == "setup" and report.failed):
            if report.passed:
                self.line[report.nodeid] = "PASSES TODAY (not a failing test)"
            else:
                text = report.longreprtext if hasattr(report, "longreprtext") else str(report.longrepr)
                last = [ln for ln in text.strip().splitlines() if ln.strip()]
                self.line[report.nodeid] = (last[-1] if last else "failed")[:140]


def main() -> int:
    c = Collector()
    code = pytest.main([str(HERE), "-q", "-p", "no:cacheprovider", "--tb=line", "-x", "--maxfail=1000"], plugins=[c])
    by_key: dict[str, list[str]] = defaultdict(list)
    for node, ids in c.ids.items():
        for i in ids:
            m = NUMBER.match(i)
            by_key[("item " + str(int(m.group(1)))) if m else i].append(node)
    bad = [n for n, ln in c.line.items() if not ln.startswith("MISSING FEATURE")]
    missing_items = [n for n in range(1, 44) if f"item {n}" not in by_key]
    out = ["# Pure projection: spec item to test, with the current failure line", "",
           "Generated by `tests/projection/make_index.py` from the `spec_item` markers. Source of truth for the items:",
           "`specs/capture-everything/pure-projection.md` in the design notes (draft 6). Every test below fails today with",
           "`MISSING FEATURE: ...` while its feature is unbuilt (a precondition that reads the repository before any database is made); a test whose feature",
           "is built shows `PASSES TODAY`, or the real assertion failure when the build is wrong or incomplete.", "",
           f"Tests: {len(c.ids)}. Failing as a missing feature: {len(c.line) - len(bad)}. Passing or failing on a built feature: {len(bad)}.", ""]
    def section(title, keys):
        out.extend([f"## {title}", "", "| Spec item | Test id | Failure today |", "|---|---|---|"])
        for k in keys:
            for node in by_key[k]:
                out.append(f"| {k} | `{node.split('::', 1)[1]}` in `{node.split('::')[0].split('/')[-1]}` | {c.line.get(node, 'not run')} |")
        out.append("")
    nums = sorted((k for k in by_key if k.startswith("item ")), key=lambda k: int(k.split()[1]))
    section("Reader cutover, numbered items 1 to 43 (item 5 is the sender's send-time checks; item 39 is its stop check)", nums)
    section("The nine record gates", [k for k in sorted(by_key) if k.startswith("gate")])
    section("Finding C1: refused posts derive no intent", [k for k in sorted(by_key) if k.startswith("C1.")])
    section("Sender skips (finding C2), one per old reason", [k for k in sorted(by_key) if re.match(r"^5\.", k)])
    mig = [k for k in sorted(by_key) if re.match(r"^00\d\d\.", k) or k.startswith(("purity.", "erasure.", "M6."))]
    section("Migration yes/no tests, proof of purity, erasure stop, row security", mig)
    stubs = []
    for f in sorted(HERE.glob("test_*.py")):
        cur = None
        for ln in f.read_text().splitlines():
            if ln.startswith("def test_"):
                cur = ln.split("(")[0][4:]
            if "ADAPTER TO COMPLETE" in ln and cur:
                stubs.append(f"- `{f.name}::{cur}`: {ln.split('ADAPTER TO COMPLETE:')[1].strip(' \",')[:150]}")
    out.extend(["## Tests that stop at an adapter once their feature exists", "",
                "Each fails today at its precondition (MISSING FEATURE). Once the feature is built it fails again, by name, with `ADAPTER TO COMPLETE`,",
                "because the design fixes the behaviour but not the call shape (the loader's argument list, the watermark job, the backfill job, the",
                "restore job). The builder completes the adapter in the same change that creates the call shape.", ""] + sorted(set(stubs)) + [""])
    (HERE / "INDEX.md").write_text("\n".join(out) + "\n")
    print(f"wrote {HERE / 'INDEX.md'}: {len(c.ids)} tests, {len(bad)} not failing for a missing feature, items without a test: {missing_items}")
    for n in bad:
        print("WRONG REASON:", n, "->", c.line[n])
    return 1 if bad or missing_items else 0


if __name__ == "__main__":
    sys.exit(main())
